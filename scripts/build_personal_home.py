#!/usr/bin/env python3
"""Build the personal homepage from the pinned AequAI Film B reference.

Run locally with python3 scripts/build_personal_home.py. The reference is
immutable; personal content and routing live here. No source checkout needed.
"""
from pathlib import Path
from bs4 import BeautifulSoup, Comment
from personal_content import apply_personal_content

ROOT = Path(__file__).resolve().parents[1]
soup = BeautifulSoup((ROOT / 'scripts/reference/aequai-home.html').read_text(), 'html.parser')
for comment in soup.find_all(string=lambda value: isinstance(value, Comment)):
    comment.extract()
soup.insert(1, Comment(' Generated by scripts/build_personal_home.py from the pinned AequAI Film B reference. '))
soup.title.string = 'Ali Osman Ozen | AI Adoption Architect'
soup.select_one('link[rel=canonical]')['href'] = 'https://0xozen.github.io/'
soup.select_one('meta[name=description]')['content'] = 'Ali Osman Ozen, AI Adoption Architect in Cologne. Workflow design, agent governance, practical AI adoption and technology-to-business translation.'
for key, value in {'og:title': str(soup.title.string), 'og:description': soup.select_one('meta[name=description]')['content'], 'og:type': 'website', 'og:url': 'https://0xozen.github.io/', 'og:image': 'https://0xozen.github.io/assets/og-image.svg'}.items():
    tag = soup.new_tag('meta', property=key, content=value)
    soup.head.append(tag)

# Keep section IDs stable: the original motion engine uses them as anchors.
sections = [
    ('svc-diagnostic', 'Control Map', 'AI adoption mapping', 'See where AI enters the work.', 'I help operations, product, and transformation leaders map real AI use: workflows, owners, tools, decisions and handoffs. The interactive map is a synthetic example of that approach.'),
    ('svc-foundation', 'Workflows', 'Workflow design', 'Put the work in order before AI.', 'My focus is the operating layer between leadership intent and daily team behavior: queues, requests, knowledge, data quality and evidence. Clear sources and accountable owners come before more automation.'),
    ('svc-safety', 'Authority', 'Agent authority', 'Make permission boundaries visible.', 'I work on the distinction between what an agent may read, draft, recommend and execute. Human approval, logs, escalation and recovery belong in the workflow from the beginning.'),
    ('svc-governance', 'Governance', 'Practical governance', 'Rules a team can explain.', 'Allowed, review-first and not-allowed uses; named owners; data boundaries; evidence and a review rhythm. I translate governance questions into operating routines managers and teams can understand.'),
    ('svc-literacy', 'Literacy', 'AI literacy & enablement', 'Translate tools into judgement.', 'My interest is practical AI adoption: help non-technical leaders understand capability, effort, risk and ownership, then connect the decision to the work their teams already do.'),
    ('svc-pilot', 'Prototypes', 'Workflow prototypes', 'Test the boundary before the action.', 'I explore bounded workflows with synthetic inputs, visible human gates and local evidence. This demonstration rehearses a plan, revision and approval; it is a portfolio study rather than a client result.'),
    ('svc-partner', 'Review', 'Evidence & recovery', 'Keep the operating model current.', 'A workflow needs evidence that can be reviewed, a baseline that can be questioned and a way back. My approach keeps exceptions, permission changes and learning visible before a broader rollout.'),
    ('svc-dpp', 'Signals', 'Research & signal mapping', 'Keep every claim close to its source.', 'I turn web, market and policy signals into reviewable adoption insight with sources attached. The product-data example illustrates evidence provenance, missing information and questions that require a specialist.'),
    ('svc-tokenization', 'Web3', 'Web3 / RWA exploration', 'Start with the use case.', 'I explore emerging-technology strategy and RWA tokenization by asking what a token would represent, which rights matter and whether a simpler record would serve the use case. This is an illustrative decision model.'),
]
for section_id, label, name, heading, body in sections:
    el = soup.select_one('#' + section_id)
    el['data-label'] = label
    el.select_one('.ns-name').string = name
    el.select_one('h2 .line').string = heading
    el.select_one('.ns-body').string = body
    el.select_one('.ns-meta').clear()
    el.select_one('.ns-meta').append('Portfolio focus · ' + label)
    note = el.select_one('.ns-not')
    if note:
        note.clear()
        note.append('Illustrative study · synthetic examples, no client outcome claimed.')
    more = el.select_one('.ns-more')
    more.clear()
    more.append(BeautifulSoup('<a class="le-button ns-call" href="mailto:ali.ozen@rwth-aachen.de">Talk to Ali</a> <a class="ns-link" href="department-adoption.html">Explore the adoption model →</a>', 'html.parser'))
for a, (_, label, name, _, _) in zip(soup.select('#ns-nl a'), sections):
    a['title'] = name
    a.span.string = label
soup.select_one('#ns-nl')['aria-label'] = 'Portfolio focus areas'
soup.select_one('.ns-plain').string = 'Intake · Requests · Knowledge · Reconcile · Evidence · Local model study'

for el in soup.select('.le-signature'):
    el.string = 'Ali Osman Ozen · AI Adoption Architect'
for el in soup.select('.fbh-lede'):
    el.string = 'I turn scattered AI use into owned workflows, clear approvals and visible evidence.'
for el in soup.select('.le-title'):
    lines = el.select('.line > span')
    lines[0].string = 'Turn scattered AI'
    lines[1].string = 'into owned workflows.'
for el in soup.select('#fbh-hero .le-button, .fbh-nojs .le-button'):
    label = 'Explore my approach' if 'le-button--primary' in el.get('class', []) else 'See my focus areas'
    for text in list(el.find_all(string=True, recursive=False)):
        text.replace_with(label + ' ')
start = soup.select_one('#start')
start['data-label'] = 'Contact'
start.select_one('.ns-meta').string = 'Ali Osman Ozen · Cologne, Germany'
start.select_one('h2 .line').string = 'Let’s make the next step clear.'
start.select_one('h2 .muted').string = 'One conversation, grounded in the work.'
start.select_one('.ns-body').string = 'Reach me for AI adoption, workflow design, governance, product operations, digital transformation and emerging-technology strategy roles.'
start.select_one('.ns-actions').clear()
start.select_one('.ns-actions').append(BeautifulSoup('<a class="le-button le-button--primary" href="mailto:ali.ozen@rwth-aachen.de">Email Ali</a> <a class="le-button" href="https://linkedin.com/in/0xozen">LinkedIn ↗</a>', 'html.parser'))
start.select_one('.ns-not').string = 'Based in Cologne · working at the intersection of technology and business.'

# Preserve the original menu interaction, replacing its company catalogue.
menus = [
    ('services', 'Focus', [(name, '#' + sid, heading) for sid, _, name, heading, _ in sections]),
    ('solutions', 'Work', [('Department adoption', 'department-adoption.html', 'The manager’s operating model for AI adoption.'), ('Workflow prototype', '#svc-pilot', 'Synthetic rehearsal, approval and revision.'), ('Control map', '#svc-diagnostic', 'Explore owners, tools and boundaries.')]),
    ('learn', 'Writing', [('Writing archive', 'writing-archive.html', 'Notes on adoption, governance and operating models.'), ('Research & signals', '#svc-dpp', 'Sources, evidence gaps and questions.'), ('Web3 / RWA', '#svc-tokenization', 'Use-case exploration and simpler alternatives.')]),
    ('company', 'About', [('Ali Osman Ozen', '#start', 'AI Adoption Architect · Cologne, Germany.'), ('GitHub', 'https://github.com/0xOzen', 'Projects and code.'), ('LinkedIn', 'https://linkedin.com/in/0xozen', 'Professional profile.'), ('AequAI', 'https://www.aequai.com/', 'My AI adoption project and the design source for this site.')]),
]
for key, label, items in menus:
    trigger = soup.select_one('#lv-menu-' + key + '-trigger')
    trigger.contents[0].replace_with(label)
    panel = soup.select_one('#lv-menu-' + key)
    panel.clear()
    groups = [items[i:i + 3] for i in range(0, len(items), 3)]
    group_html = ''.join('<div class="mn-group">' + ''.join(f'<a class="mn-item" href="{href}"><span class="mn-t">{title}</span><span class="mn-d">{desc}</span></a>' for title, href, desc in group) + '</div>' for group in groups)
    panel.append(BeautifulSoup('<div class="mn-in"><div class="mn-aside"><p class="mn-label">' + label + '</p><p class="mn-intro">Ali Osman Ozen<br>AI Adoption Architect<br>Cologne, Germany</p></div><div class="mn-main">' + group_html + '</div><div class="mn-card"><p class="mn-label">Get in touch</p><p class="mn-card-t">From scattered use to clear ownership.</p><a class="mn-cta" href="mailto:ali.ozen@rwth-aachen.de">Email Ali ↗</a></div></div>', 'html.parser'))

footer = soup.select_one('#e-footer')
footer.select_one('.fbf-k').string = 'Ali Osman Ozen · Cologne, Germany'
footer.select_one('.fbf-h').clear()
footer.select_one('.fbf-h').append(BeautifulSoup('Useful AI.<br><span>Visible responsibility.</span>', 'html.parser'))
footer.select_one('.fbf-actions').clear()
footer.select_one('.fbf-actions').append(BeautifulSoup('<a class="le-button le-button--primary" href="mailto:ali.ozen@rwth-aachen.de">Email Ali</a><a class="le-button" href="https://linkedin.com/in/0xozen">LinkedIn ↗</a>', 'html.parser'))
footer.select_one('.fbf-mail').string = 'ali.ozen@rwth-aachen.de'
footer.select_one('.fbf-nav').clear()
for _, label, items in menus:
    footer.select_one('.fbf-nav').append(BeautifulSoup('<div class="fbf-col"><p class="fbf-k">' + label + '</p><ul>' + ''.join(f'<li><a href="{href}">{title}</a></li>' for title, href, _ in items) + '</ul></div>', 'html.parser'))
footer.select_one('.fbf-bottom > span').string = '© 2026 Ali Osman Ozen · AI adoption, with visible responsibility.'
footer.select_one('.fbf-bottom nav').clear()
footer.select_one('.fbf-bottom nav').append(BeautifulSoup('<a href="https://github.com/0xOzen">GitHub</a><a href="https://www.aequai.com/">AequAI</a><a href="#top">Back to top ↑</a>', 'html.parser'))
soup.select_one('.lv-logo-motion')['aria-label'] = 'Ali Osman Ozen — Home'
soup.select_one('.lv-plate')['aria-label'] = 'Square particle field'
soup.select_one('#track')['aria-label'] = 'My approach to AI adoption, one step per scroll'

routes = {'company.html': '#start', 'contact.html': '#start', 'ai-adoption-diagnostic.html': '#svc-diagnostic', 'services.html': '#nine-steps'}
for a in soup.select('a[href]'):
    href = a['href']
    if href.startswith('mailto:ozen@aequai.com'):
        a['href'] = 'mailto:ali.ozen@rwth-aachen.de'
    elif href in routes:
        a['href'] = routes[href]
for el in soup.select('.lv-menu-fallback'):
    el.clear()
    el.append(BeautifulSoup('<a href="#nine-steps">Focus</a><a href="department-adoption.html">Work</a><a href="writing-archive.html">Writing</a><a href="#start">Contact</a>', 'html.parser'))

apply_personal_content(soup, ROOT)
html = str(soup)
# The film's generated copy and synthetic decision file are runtime strings.
for old, new in {
    'Know where AI fits.': 'Turn scattered AI',
    'And where it does not.': 'into owned workflows.',
    'AequAI / Decision file': '0xOzen / Decision file',
    'sig:"AequAI"': 'sig:"Ali Osman Ozen"',
    'your own model, fine-tuned locally': 'local model study',
    'We start with one outcome and one workflow.': 'I start with one outcome and one workflow.',
    'We map the work,': 'Map the work,',
}.items():
    html = html.replace(old, new)
html = html.replace('assets/', 'assets/aequai-home/')
html = html.replace('https://0xozen.github.io/assets/aequai-home/og-image.svg', 'https://0xozen.github.io/assets/og-image.svg')
for asset in ['personal-content.css', 'personal-content.js', 'personal-model.js', 'adoption-gap-diagram.css', 'adoption-gap-diagram.js']:
    html = html.replace('assets/aequai-home/' + asset, 'assets/' + asset)
# Let native scrolling reach the personal diagrams and composer after the film.
html = html.replace('scrollY>=a()[0]-2', 'scrollY>=a()[0]-2&&scrollY<document.querySelector(".po-content").offsetTop-innerHeight*.2')
html = html.replace('h=()=>!!t&&!s()', 'h=()=>innerWidth>820&&!!t&&!s()')
html = html.replace('return o&&C.push(document.documentElement.scrollHeight-innerHeight),C', 'return C.push(document.querySelector(".po-content").offsetTop),o&&C.push(document.documentElement.scrollHeight-innerHeight),C')
html = html.replace('<section aria-labelledby="start-h"', '<span id="contact"></span><section aria-labelledby="start-h"')
(ROOT / 'index.html').write_text(html.rstrip() + '\n')
print('Built personal index.html with the original Film B and all nine visual studies.')
