#!/usr/bin/env python3
"""Preserve pinned personal content inside the shared AequAI homepage shell."""
from pathlib import Path
from copy import deepcopy
import re
from bs4 import BeautifulSoup, Comment
ROOT = Path(__file__).resolve().parents[1]
home = BeautifulSoup((ROOT/'index.html').read_text(), 'html.parser')
for source in sorted((ROOT/'scripts/reference/subpages').glob('*.html')):
    old = BeautifulSoup(source.read_text(), 'html.parser')
    page = BeautifulSoup('<!doctype html><html lang="en" data-theme="light"><head></head><body></body></html>', 'html.parser')
    page.html['data-page'] = 'writing' if source.name.startswith('writing') else 'adoption'
    page.head.replace_with(deepcopy(home.head))
    page.title.string = old.title.string
    for el in page.select('meta[property^="og:"],link[rel="canonical"],link[href="assets/personal-content.css"],link[href="assets/adoption-gap-diagram.css"]'):
        el.decompose()
    for meta in old.select('meta[property^="og:"],meta[name^="twitter:"]'):
        existing = page.head.find("meta", attrs={"name":meta.get("name")}) if meta.get("name") else None
        if existing: existing.decompose()
        page.head.append(deepcopy(meta))
    desc = old.select_one('meta[name="description"]')
    if desc: page.select_one('meta[name="description"]')['content'] = desc['content']
    page.head.append(BeautifulSoup(f'<link rel="canonical" href="https://0xozen.github.io/{source.name}">', 'html.parser'))
    legacy = page.new_tag('style');legacy.string = '@layer personal-legacy {\n' + '\n'.join(x.text for x in old.find_all('style')) + '\n}'
    page.head.append(legacy)
    page.head.append(BeautifulSoup('<link rel="stylesheet" href="assets/personal-subpages.css">', 'html.parser'))
    # Shared theme storage applies before paint.
    for script in page.head.find_all('script'): script.decompose()
    init = page.new_tag('script');init.string = 'try{document.documentElement.dataset.theme=localStorage.getItem("aequai.site.theme")||"light"}catch(e){}'
    page.head.append(init)
    page.body.attrs = {'class':['lv','le','gk-scope','fbh','ps-page'], 'data-gk-accent':'amber','data-gk-quiet':'','data-gk-doc':'','id':'top'}
    def shared(selector):
        el = deepcopy(home.select_one(selector))
        for link in el.select('a[href^="#"]'):
            if link['href'] != '#top': link['href'] = 'index.html'+link['href']
        return el
    for selector in ['.lv-plate','.lv-head','.lv-logo-motion']:
        page.body.append(shared(selector))
    logo = page.select_one('.lv-logo-motion'); mark=deepcopy(home.select_one('.fbf-mark'));mark['class']=['ps-logo'];mark['width']='49';mark['height']='49';logo.append(mark)
    main = deepcopy(old.main);main['id']='le-content';main['class']=['ps-main'];page.body.append(main)
    hero = main.select_one('.hero');hero['class'].append('ps-hero')
    field = page.new_tag('canvas', attrs={'class':'ps-particles','aria-hidden':'true'});hero.insert(0,field)
    badge = hero.select_one('.cmd, .eyebrow')
    if badge: badge['class']=['ps-eyebrow'];badge.string = 'Writing / Archive' if source.name.startswith('writing') else 'Work / Department adoption'
    # Preserve text and links while removing terminal chrome.
    for el in main.select('.traffic'): el.decompose()
    for panel in main.select('.command-shell'):
        panel['aria-label']='Writing series and source status'
    for el in old.body.find_all(recursive=False):
        if el.name in ['svg','noscript'] or el.get('id') in ['cmdkBackdrop','readBar'] or 'read-bar' in el.get('class',[]):
            page.body.append(deepcopy(el))
    footer=shared('#e-footer');footer['id']='contact';page.body.append(footer)
    page.body.append(deepcopy(home.select_one('.lv-menu-shade')))
    for src in ['assets/aequai-home/lens-menu.js?v=20260913','assets/personal-shell.js']:
        page.body.append(page.new_tag('script',src=src,defer=''))
    for script in old.body.find_all('script'):
        if script.get('src'): page.body.append(deepcopy(script));continue
        text=script.text
        text=re.sub(r'/\* Theme picker \*/.*?(?=/\* Mobile topbar \*/)', '',text,flags=re.S)
        text=re.sub(r'function setTheme\(t\) \{.*?\n      \}', 'function setTheme(t) { window.PersonalSite.setTheme(t === "terminal" ? "dark" : "light"); }',text,flags=re.S)
        text=text.replace('Terminal · data field','Dark theme').replace('Dark · Linear','Light theme').replace('Theme: Terminal','Theme: Dark').replace('Theme: Dark\'); } }','Theme: Light\'); } }')
        new=page.new_tag('script');new.string=text;page.body.append(new)
    page.insert(1,Comment(' Generated by scripts/build_personal_subpages.py; content pinned in scripts/reference/subpages. '))
    (ROOT/source.name).write_text(re.sub(r'(?m)^[ \t]+$', '', str(page))+'\n')
    print('Built',source.name)
